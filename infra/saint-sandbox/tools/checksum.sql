-- Huella de cada tabla (para comprobar que reset restaura el estado original).
USE SAINT_DEMO;
GO
SET NOCOUNT ON;
SELECT 'SAINSTA' AS tabla, COUNT(*) AS filas, CHECKSUM_AGG(BINARY_CHECKSUM(*)) AS huella FROM dbo.SAINSTA
UNION ALL SELECT 'SADEPO', COUNT(*), CHECKSUM_AGG(BINARY_CHECKSUM(*)) FROM dbo.SADEPO
UNION ALL SELECT 'SAPROD', COUNT(*), CHECKSUM_AGG(BINARY_CHECKSUM(*)) FROM dbo.SAPROD
UNION ALL SELECT 'SAEXIS', COUNT(*), CHECKSUM_AGG(BINARY_CHECKSUM(*)) FROM dbo.SAEXIS
UNION ALL SELECT 'SACLIE', COUNT(*), CHECKSUM_AGG(BINARY_CHECKSUM(*)) FROM dbo.SACLIE
UNION ALL SELECT 'SAPEDIDO', COUNT(*), CHECKSUM_AGG(BINARY_CHECKSUM(*)) FROM dbo.SAPEDIDO
UNION ALL SELECT 'SAITEMPED', COUNT(*), CHECKSUM_AGG(BINARY_CHECKSUM(*)) FROM dbo.SAITEMPED
UNION ALL SELECT 'SAFACT', COUNT(*), CHECKSUM_AGG(BINARY_CHECKSUM(*)) FROM dbo.SAFACT
UNION ALL SELECT 'SAITEMFAC', COUNT(*), CHECKSUM_AGG(BINARY_CHECKSUM(*)) FROM dbo.SAITEMFAC
UNION ALL SELECT 'SAACXC', COUNT(*), CHECKSUM_AGG(BINARY_CHECKSUM(*)) FROM dbo.SAACXC;
GO
